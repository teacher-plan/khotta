import os
exec(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'summary2.py'), encoding='utf-8').read())
def T(k, v): return f'{k}{V(v)}'

HD = header('٢-٥', 'كتابة المعادلات وحلّها', 'الوحدة الثانية: العبارات الجبرية والمعادلات والصيغ',
            'أحلّ المعادلة بالعمليات العكسية على طرفيها وأتحقّق من الحل، وأكتب معادلةً من وصفٍ لفظي ثم أحلّها')

p1 = ''.join([
 sec(1, 'المعادلة وحلّها',
  rule(f'<b>المعادلة</b> طرفان بينهما إشارة التساوي، مثل {M(V("س"), PL, "٥", EQ, "١٢")}.<br>'
       f'<b>حلّ المعادلة</b> هو إيجاد قيمة المتغيّر فيها، وحلّ هذه المعادلة {M(V("س"), EQ, "٧")}.<br>'
       'المعادلة مثل <b>ميزانٍ متوازن</b>: ما نجريه على أحد الطرفين نجريه على الآخر.')),
 sec(2, 'العمليات العكسية',
  rule('نتخلّص من العدد الموجود مع المتغيّر بالعملية <b>العكسية</b>، ونجريها على <b>الطرفين معاً</b>.', '↔️'),
  table(['مع المتغيّر', 'العكسية على الطرفين', 'مثال'], [
   ['جمع', 'نطرح', M(V('س'), PL, '٥', EQ, '١٢', '←', V('س'), EQ, '٧')],
   ['طرح', 'نجمع', M(V('س'), MI, '٣', EQ, '١٢', '←', V('س'), EQ, '١٥')],
   ['ضرب', 'نقسم', M(T('٣', 'س'), EQ, '١٢', '←', V('س'), EQ, '٤')],
   ['قسمة', 'نضرب', M(FR(V('س'), '٢'), EQ, '٤', '←', V('س'), EQ, '٨')]], 'inv')),
 sec(3, 'مثال محلول: معادلة فيها جمع',
  example(f'حلّ المعادلة {M(V("س"), PL, "٦", EQ, "١٤")} وتحقّق من الحل.', [
   (M(V('س'), PL, '٦', MI, '٦', EQ, '١٤', MI, '٦'), 'نطرح ٦ من الطرفين لنتخلّص من + ٦'),
   (M(V('س'), EQ, '٨'), '١٤ ناقص ٦ يساوي ٨'),
   (M('٨', PL, '٦', EQ, '١٤'), 'نتحقّق: نعوّض س = ٨ في المعادلة، فيتساوى الطرفان')], M(V('س'), EQ, '٨'))),
 sec(4, 'مثال محلول: معادلة فيها ضرب وأخرى فيها قسمة',
  example(f'حلّ المعادلتين {M(T("٥", "س"), EQ, "٣٥")} و {M(FR(V("ص"), "٤"), EQ, "٦")}.', [
   (M(FR(T('٥', 'س'), '٥'), EQ, FR('٣٥', '٥'), '←', V('س'), EQ, '٧'), '٥س تعني ٥ × س، فنقسم الطرفين على ٥، ونتحقّق: ٥ × ٧ يساوي ٣٥'),
   (M(FR(V('ص'), '٤'), X, '٤', EQ, '٦', X, '٤', '←', V('ص'), EQ, '٢٤'), 'ص مقسومة على ٤، فنضرب الطرفين في ٤، ونتحقّق: ٢٤ ÷ ٤ يساوي ٦')], f'{M(V("س"), EQ, "٧")} ، {M(V("ص"), EQ, "٢٤")}')),
])
p2 = ''.join([
 sec(5, 'مثال محلول: معادلة بخطوتين',
  example(f'حلّ المعادلة {M(T("٣", "س"), MI, "٤", EQ, "١١")} وتحقّق من الحل.', [
   (M(T('٣', 'س'), MI, '٤', PL, '٤', EQ, '١١', PL, '٤'), 'أولاً نتخلّص من − ٤ بإضافة ٤ إلى الطرفين'),
   (M(T('٣', 'س'), EQ, '١٥'), 'نبسّط الطرفين'),
   (M(V('س'), EQ, '٥'), 'ثانياً نقسم الطرفين على ٣'),
   (M('٣', X, '٥', MI, '٤', EQ, '١١'), 'نتحقّق: ١٥ ناقص ٤ يساوي ١١، فالحل صحيح')], M(V('س'), EQ, '٥'))),
 sec(6, 'مثال محلول: كتابة معادلة من وصفٍ لفظي',
  example('أفكّر في عدد، إذا قسمته على ٤ ثم أضفت إليه ٥ يكون الناتج ٩. ما العدد؟', [
   (M(FR(V('س'), '٤'), PL, '٥', EQ, '٩'), 'نرمز للعدد بالحرف س، ونكتب كل جزءٍ نقرؤه: نقسم على ٤، ثم نضيف ٥، والناتج ٩'),
   (M(FR(V('س'), '٤'), EQ, '٤'), 'نطرح ٥ من الطرفين'),
   (M(V('س'), EQ, '١٦'), 'نضرب الطرفين في ٤، ونتحقّق: ١٦ ÷ ٤ + ٥ يساوي ٩')], 'العدد ١٦')),
 sec(7, 'أخطاءٌ شائعة',
  warn([(f'{M(V("س"), PL, "٥", MI, "٥", EQ, "١٢")}', f'{M(V("س"), PL, "٥", MI, "٥", EQ, "١٢", MI, "٥")}', 'نجري العملية على الطرفين معاً، لا على طرفٍ واحد'),
        (f'{M(V("س"), MI, "٣", EQ, "١٢")} إذن {M(V("س"), EQ, "٩")}', f'{M(V("س"), EQ, "١٥")}', 'العملية العكسية للطرح هي الجمع'),
        (f'{M(T("٢", "س"), PL, "٤", EQ, "١٦")} إذن {M(V("س"), PL, "٤", EQ, "٨")}', f'{M(T("٢", "س"), EQ, "١٢")} ثم {M(V("س"), EQ, "٦")}', 'نتخلّص من الجمع والطرح أولاً، ثم من الضرب والقسمة')])),
 practice([f'حلّ {M(V("س"), MI, "١٢", EQ, "١٤")}', f'حلّ {M(FR(V("س"), "٩"), EQ, "٧")}',
           f'حلّ {M(T("٤", "م"), PL, "١", EQ, "١٧")}', 'أفكّر في عدد إذا ضربته في ٤ ثم أضفت إليه ٢ يكون الناتج ٢٦'],
          [M(V('س'), EQ, '٢٦'), M(V('س'), EQ, '٦٣'), M(V('م'), EQ, '٤'), M(T('٤', 'س'), PL, '٢', EQ, '٢٦') + ' ، س = ٦']),
])
build(os.path.join(HERE, 'ملخص_كتابة_المعادلات_وحلها.html'), 'ملخص كتابة المعادلات وحلها', [(HD, p1), (HD, p2)])
