import os
exec(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'summary2.py'), encoding='utf-8').read())
def T(k, v): return f'{k}{V(v)}'
def B(k, *inner): return M(k, G(*inner))

HD = header('٢-٣', 'فكّ الأقواس', 'الوحدة الثانية: العبارات الجبرية والمعادلات والصيغ',
            'أفكّ الأقواس في عبارةٍ جبرية بضرب الحدّ الموجود خارج الأقواس في كل حدٍّ بداخلها')

p1 = ''.join([
 sec(1, 'معنى الأقواس في العبارة الجبرية',
  rule(f'العدد المكتوب ملاصقاً للقوس يعني <b>الضرب</b>، فالعبارة {B("٤", V("س"), PL, "٣")} تعني {M("٤", X, G(V("س"), PL, "٣"))}.<br>'
       f'ولا نكتب علامة الضرب عادةً، بل نكتب العدد ثم القوس مباشرةً.'),
  p(f'إزالة القوسين بكتابة العبارة دون أقواس تُسمّى <b>فكّ الأقواس</b>، وتُسمّى أيضاً <b>الضرب خارج الأقواس</b>.')),
 sec(2, 'قاعدة فكّ الأقواس',
  rule(f'نضرب <b>الحدّ الموجود خارج الأقواس</b> في <b>كل حدٍّ</b> بداخلها، ونُبقي الإشارة بين الحدّين كما هي.<br>'
       f'{B("ك", "أ", PL, "ب")} {EQ} {M("ك", X, "أ", PL, "ك", X, "ب")}، و {B("ك", "أ", MI, "ب")} {EQ} {M("ك", X, "أ", MI, "ك", X, "ب")}.', '✖️'),
  p(f'<b>لماذا نضرب في الحدّين معاً؟</b> مستطيلٌ عرضه ٤ وطوله {M(V("س"), PL, "٣")} يتكوّن من جزأين: مساحة الأول {M("٤", X, V("س"), EQ, T("٤", "س"))} ومساحة الثاني {M("٤", X, "٣", EQ, "١٢")}، '
    f'فمساحته كلّها {B("٤", V("س"), PL, "٣")} {EQ} {M(T("٤", "س"), PL, "١٢")}.'),
  table(['×', V('س'), '٣'], [['٤', T('٤', 'س'), '١٢']], 'area')),
 sec(3, 'مثال محلول: القوس فيه جمع',
  example(f'فكّ الأقواس: {B("٥", V("ص"), PL, "٤")}.', [
   (M('٥', X, V('ص'), PL, '٥', X, '٤'), 'نضرب ٥ في الحدّ الأول ص، ثم نضرب ٥ في الحدّ الثاني ٤'),
   (M(T('٥', 'ص'), PL, '٢٠'), '٥ × ص نكتبها ٥ص، و ٥ × ٤ يساوي ٢٠، والإشارة + تبقى كما هي')], M(T('٥', 'ص'), PL, '٢٠'))),
 sec(4, 'مثال محلول: القوس فيه طرح',
  example(f'فكّ الأقواس: {B("٧", V("ك"), MI, "٣")}.', [
   (M('٧', X, V('ك'), MI, '٧', X, '٣'), 'نضرب ٧ في كل حدٍّ داخل القوسين، ونكتب إشارة الطرح بينهما كما هي'),
   (M(T('٧', 'ك'), MI, '٢١'), '٧ × ك يساوي ٧ك، و ٧ × ٣ يساوي ٢١')], M(T('٧', 'ك'), MI, '٢١'))),
])
p2 = ''.join([
 sec(5, 'مثال محلول: حدٌّ له معامل داخل القوسين',
  example(f'اضرب خارج الأقواس: {B("٤", T("٣", "ع"), PL, "٢")}.', [
   (M('٤', X, T('٣', 'ع'), PL, '٤', X, '٢'), 'نضرب ٤ في الحدّ ٣ع، ثم نضرب ٤ في ٢'),
   (M(T('١٢', 'ع'), PL, '٨'), 'في ٤ × ٣ع نضرب العددين ٤ × ٣ يساوي ١٢ ونُبقي المتغيّر ع، و ٤ × ٢ يساوي ٨')], M(T('١٢', 'ع'), PL, '٨'))),
 sec(6, 'مثال محلول: العدد أولاً داخل القوسين',
  example(f'اضرب خارج الأقواس: {B("٦", "٥", MI, T("٢", "م"))}.', [
   (M('٦', X, '٥', MI, '٦', X, T('٢', 'م')), 'نضرب ٦ في ٥، ثم نضرب ٦ في ٢م، ونُبقي إشارة الطرح'),
   (M('٣٠', MI, T('١٢', 'م')), '٦ × ٥ يساوي ٣٠، و ٦ × ٢م يساوي ١٢م'),
   (M('٣٠', MI, T('١٢', 'م')), 'لا نطرح ١٢م من ٣٠ لأنهما حدّان غير متشابهين، فهذه أبسط صورة')], M('٣٠', MI, T('١٢', 'م')))),
 sec(7, 'أخطاءٌ شائعة',
  warn([(f'{B("٤", V("س"), PL, "٣")} {EQ} {M(T("٤", "س"), PL, "٣")}', f'{M(T("٤", "س"), PL, "١٢")}', 'يجب أن نضرب ٤ في الحدّ الثاني ٣ أيضاً'),
        (f'{B("٤", V("س"), PL, "٣")} {EQ} {M(T("٤", "س"), PL, "٧")}', f'{M(T("٤", "س"), PL, "١٢")}', 'نضرب ٤ × ٣، ولا نجمع ٤ + ٣'),
        (f'{B("٣", V("ص"), MI, "١")} {EQ} {M(T("٣", "ص"), PL, "٢")}', f'{M(T("٣", "ص"), MI, "٣")}', 'نضرب ٣ × ١ ونُبقي إشارة الطرح، ولا نطرح ٣ ناقص ١'),
        (f'{M("١٢", MI, T("٦", "س"), EQ, T("٦", "س"))}', f'{M("١٢", MI, T("٦", "س"))}', '١٢ و ٦س غير متشابهين، فلا يُطرح أحدهما من الآخر')])),
 practice([f'فكّ الأقواس {B("٣", V("ن"), PL, "٧")}', f'فكّ الأقواس {B("٨", "٢", MI, V("ل"))}',
           f'اضرب خارج الأقواس {B("٥", T("٤", "ر"), MI, "٣")}', f'اضرب خارج الأقواس {B("٩", "٢", PL, T("٣", "ط"))}'],
          [M(T('٣', 'ن'), PL, '٢١'), M('١٦', MI, T('٨', 'ل')), M(T('٢٠', 'ر'), MI, '١٥'), M('١٨', PL, T('٢٧', 'ط'))]),
])
build(os.path.join(HERE, 'ملخص_فك_الأقواس.html'), 'ملخص فك الأقواس', [(HD, p1), (HD, p2)])
