import os
exec(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'summary2.py'), encoding='utf-8').read())

HD = header('٢-١', 'كتابة العبارات الجبرية', 'الوحدة الثانية: العبارات الجبرية والمعادلات والصيغ',
            'أستخدم حرفاً لتمثيل عددٍ مجهول، وأكتب عبارةً جبرية من وصفٍ لفظي، وأصف عبارةً جبرية بالكلمات')

p1 = ''.join([
 sec(1, 'المتغيّر والعبارة الجبرية',
  rule(f'<b>المتغيّر</b> حرفٌ يمثّل عدداً مجهولاً لا نعرف قيمته، مثل {M(V("س"))} أو {M(V("ع"))}.<br><b>العبارة الجبرية</b> تتكوّن من أرقامٍ ومتغيّراتٍ وعمليات، مثل {M(V("ن"), PL, "٤")} و {M("٣" + V("ك"))}، ولا تحتوي على علامة التساوي (=).'),
  p(f'إذا كان في علبةٍ {M(V("ع"))} قلماً وأخذنا منها ٣ أقلام، فعدد الأقلام المتبقّية هو العبارة الجبرية {M(V("ع"), MI, "٣")}. أمّا {M(V("ع"), MI, "٣", EQ, "٧")} فهي معادلة وليست عبارة.')),
 sec(2, 'كلماتٌ تدلّ على العمليات',
  table(['العملية', 'كلماتٌ تدلّ عليها', 'مثال'], [
   ['+', 'أضِف، يزيد، أكثر من، أكبر من، مجموع، اشترى', f'٤ أكثر من ن: {M(V("ن"), PL, "٤")}'],
   ['−', 'اطرح، أقلّ من، أصغر من، أخذ، استخدم، أنفق', f'٤ أقلّ من ن: {M(V("ن"), MI, "٤")}'],
   ['×', 'اضرب، ضعف، مرّات، ثمن عدّة قطع', f'ضعف ن: {M("٢" + V("ن"))}'],
   ['÷', 'اقسم، نصف، ثلث، ربع، يوزّع بالتساوي', f'ربع ن: {M(FR(V("ن"), "٤"))}']])),
 sec(3, 'قواعد الكتابة',
  rule(f'في الضرب نكتب <b>العدد قبل المتغيّر</b> بلا علامة ×: {M("٣", X, V("ك"))} تُكتب {M("٣" + V("ك"))}.<br>'
       f'في القسمة نكتب <b>كسراً</b>: {M(V("ك"), DV, "٥")} تُكتب {M(FR(V("ك"), "٥"))}.<br>'
       f'في الطرح <b>الترتيب مهمّ</b>: «٥ أقلّ من ك» تعني {M(V("ك"), MI, "٥")}، و«اطرح ك من ٥» تعني {M("٥", MI, V("ك"))}.', '✏️')),
 sec(4, 'مثال محلول',
  example('عمر سلمى م سنة. اكتب عبارةً جبرية لعمر كلٍّ من أفراد عائلتها.', [
   (M('أخوها:', V('م'), PL, '٦'), 'أكبر منها بست سنوات، إذن نضيف ٦ إلى م'),
   (M('أختها:', V('م'), MI, '٣'), 'أصغر منها بثلاث سنوات، إذن نطرح ٣ من م'),
   (M('والدها:', '٤' + V('م')), 'عمره أربعة أضعاف عمرها، إذن نضرب م في ٤ ونكتب العدد أولاً'),
   (M('ابن عمّها:', FR(V('م'), '٢')), 'عمره نصف عمرها، إذن نقسم م على ٢ ونكتبها كسراً')])),
])
p2 = ''.join([
 sec(5, 'عمليتان متتاليتان والأقواس',
  rule(f'إذا كانت العملية الأولى جمعاً أو طرحاً ثم جاء بعدها ضربٌ أو قسمة، نضع العملية الأولى <b>بين قوسين</b> لتُنفَّذ أولاً.<br>'
       f'«أضِف ٣ إلى ن ثم اضرب الناتج في ٤»: {M("٤", G(V("ن"), PL, "٣"))}، و«اطرح ١ من ن ثم اقسم الناتج على ٢»: {M(FR(M(V("ن"), MI, "١"), "٢"))}.'),
  p(f'قارن: «اضرب ن في ٤ ثم أضِف ٣» تُكتب {M("٤" + V("ن"), PL, "٣")} بلا أقواس، لأنّ الضرب يُنفَّذ قبل الجمع أصلاً.')),
 sec(6, 'مثالان محلولان',
  '<div class="two">' +
  example('ثمن القلم ق ريالاً، وثمن الدفتر د ريالاً. ما ثمن ٣ أقلام ودفترين؟', [
   (M('٣' + V('ق')), 'ثمن ٣ أقلام: نضرب عدد الأقلام في ثمن القلم'),
   (M('٢' + V('د')), 'ثمن دفترين: نضرب عدد الدفاتر في ثمن الدفتر'),
   (M('٣' + V('ق'), PL, '٢' + V('د')), 'نجمع الثمنين')], M('٣' + V('ق'), PL, '٢' + V('د'), 'ريالاً')) +
  example(f'اكتب وصفاً لفظياً للعبارة {M("٢", G(V("ك"), MI, "٥"))}.', [
   (M(V('ك'), MI, '٥'), 'ما بين القوسين يُنفَّذ أولاً: نطرح ٥ من ك'),
   (M('٢', G(V('ك'), MI, '٥')), 'ثم نضرب الناتج كلّه في ٢')], 'اطرح ٥ من ك، ثم اضرب الناتج في ٢', 'من العبارة إلى الكلمات') + '</div>'),
 sec(7, 'أخطاءٌ شائعة',
  warn([(f'«٢ أقلّ من س»: {M("٢", MI, V("س"))}', f'{M(V("س"), MI, "٢")}', 'نبدأ بالعدد س ثم نطرح منه ٢'),
        (f'نكتب {M(V("س") + "٣")}', f'نكتب {M("٣" + V("س"))}', 'العدد يُكتب قبل المتغيّر دائماً'),
        (f'«أضِف ٣ ثم اضرب في ٤»: {M("٤" + V("ن"), PL, "٣")}', f'{M("٤", G(V("ن"), PL, "٣"))}', 'العملية الأولى تُحاط بقوسين حتى تُنفَّذ أولاً')])),
 practice(['نصف العدد ط', 'اضرب ر في ٥ ثم اطرح ٢', 'أضِف ٧ إلى ر ثم اقسم الناتج على ٣', f'صِف العبارة {M("٦", MI, "٢" + V("ع"))}'],
          [M(FR(V('ط'), '٢')), M('٥' + V('ر'), MI, '٢'), M(FR(M(V('ر'), PL, '٧'), '٣')), 'اضرب ع في ٢ ثم اطرح الناتج من ٦']),
])
build(os.path.join(HERE, 'ملخص_كتابة_العبارات_الجبرية.html'), 'ملخص كتابة العبارات الجبرية', [(HD, p1), (HD, p2)])
