-- إصلاح: تمكين تعدّد الكتب للمادة الواحدة
-- ══════════════════════════════════════════════════════════════════════
--
-- المشكلة
-- الحلقة الأولى تحتاج ثلاثة كتب للمادة الواحدة في الفصل. وترحيل 20260714
-- أضاف عمود book_no وقيداً فريداً رباعياً لتمكين ذلك، وأسقط القيد الفريد
-- القديم — لكنه بحث عن constraint_type = 'UNIQUE' وحده، فنجا المفتاح
-- الأساسي المبني على (grade, subject, semester) وظلّ يمنع الكتاب الثاني.
--
-- الأثر: إدراج كتاب ثانٍ لنفس المادة يُرفض بـ unique_violation. أي أن
-- ميزة الكتب الثلاثة لا تعمل اليوم رغم وجود كل ما يلزمها في الكود.
--
-- تحقّقت منه على PostgreSQL 16 بإعادة بناء الجدول ببنيته الحقيقية.
--
-- الحل
-- نستبدل المفتاح الأساسي بآخر يشمل book_no. القيد الفريد الرباعي يصير
-- عندئذٍ مكرّراً للمفتاح فنُسقطه.
--
-- ⚠️ قبل التنفيذ
-- 1) هذا يُعدّل بنية جدول إنتاج فيه ١٣ صفاً. خُذ نسخة احتياطية أولاً
--    (لوحة Supabase ← Database ← Backups).
-- 2) نفّذه كاملاً دفعة واحدة — هو داخل معاملة، فإما أن يتم كله أو لا شيء.
-- 3) الصفوف الحالية لن تتأثر: كلها book_no = 1، وتبقى فريدة بالمفتاح الجديد.
-- ══════════════════════════════════════════════════════════════════════

begin;

-- ① تحقّق أن البيانات الحالية تحتمل المفتاح الجديد (لا تكرار في الرباعي)
do $$
declare dup integer;
begin
  select count(*) into dup from (
    select grade, subject, semester, book_no
    from public.book_sources
    group by grade, subject, semester, book_no
    having count(*) > 1
  ) x;
  if dup > 0 then
    raise exception 'يوجد % تكرار في (grade, subject, semester, book_no) — أوقفنا العملية', dup;
  end if;
  raise notice '✅ البيانات الحالية تحتمل المفتاح الجديد';
end $$;

-- ② أسقط المفتاح الأساسي الثلاثي (هو المانع)
alter table public.book_sources
  drop constraint if exists book_sources_pkey;

-- ③ ضع المفتاح الرباعي مكانه
alter table public.book_sources
  add constraint book_sources_pkey
  primary key (grade, subject, semester, book_no);

-- ④ القيد الفريد الرباعي صار مكرّراً للمفتاح — نُسقطه ونوفّر فهرساً
alter table public.book_sources
  drop constraint if exists book_sources_grade_subject_semester_book_no_key;

commit;

