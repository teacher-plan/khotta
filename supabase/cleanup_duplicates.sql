-- القائمتان أصلاً. لا ثغرة فيها، لكنها تكرار أضفتُه.

drop policy if exists c1prof_own on public.cycle1_profiles;
-- يبقى: cycle1_own (كل معلمة تُدير ملفها) · cycle1_admin_select (المشرف يقرأ)


