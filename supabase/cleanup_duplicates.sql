-- ─────────────────────────────────────────────────────────────
-- ① ثلاثة فهارس متطابقة على curriculum   ✅ آمن
-- ─────────────────────────────────────────────────────────────
-- الثلاثة على (semester, subject, grade, sort) بتعريف واحد لا فرق بينه:
--   idx_curriculum_lookup   ← قائم أصلاً، نُبقيه
--   idx_curriculum_path     ← مكرّر قديم
--   curriculum_lookup       ← أنشأتُه أنا في النسخة التقديرية، خطأ مني
--
-- لا شيء في الكود يشير إلى الفهارس بأسمائها — قاعدة البيانات تختار الفهرس
-- المناسب وحدها. فحذف المكرّرين لا يمسّ أي استعلام.
--
-- الأثر: كل إضافة أو تعديل في المنهج (٢٨٩٣ صفاً) تُحدّث فهرساً واحداً بدل
-- ثلاثة، وتُسترجَع مساحة فهرسين.

drop index if exists public.curriculum_lookup;
drop index if exists public.idx_curriculum_path;


-- ─────────────────────────────────────────────────────────────
-- ② سياستان مكرّرتان على book_sources   ✅ آمن
-- ─────────────────────────────────────────────────────────────
-- في الإنتاج أربع سياسات، زوجان متطابقان تماماً:
--   "read book_sources"        = booksrc_read          (select, using true)
--   "admin write book_sources" = booksrc_admin_write   (all, is_app_admin)
--
-- المكرّران من إنشائي في النسخة التقديرية. نُسقطهما ونُبقي الأصليين.
--
-- لماذا آمن: سياسات RLS المتعددة تُجمع بـ«أو» لا بـ«و». فوجود سياستين
-- متطابقتين يعطي نفس الصلاحية تماماً، وحذف إحداهما لا يُغيّر شيئاً.

drop policy if exists booksrc_read        on public.book_sources;
drop policy if exists booksrc_admin_write on public.book_sources;


-- ─────────────────────────────────────────────────────────────
-- ③ سياسة زائدة على cycle1_profiles   ✅ آمن — مع تنبيه للمستقبل
-- ─────────────────────────────────────────────────────────────
-- الثلاث القائمة:
--   cycle1_own          (all)    auth.uid() = id          ← المعلمة تُدير ملفها
--   cycle1_admin_select (select) is_app_admin()           ← المشرف يقرأ
--   c1prof_own          (all)    id = auth.uid() OR admin ← أنشأتُها أنا
--
-- تحقّقتُ: manager.html يقرأ cycle1_profiles في موضعين فقط (سطر ٥٦٠٢ و٥٦٤٠)
-- وكلاهما select. ولا يكتب فيه أحد غير المعلمة نفسها من cycle1.html.
-- فحذف c1prof_own لا يكسر شيئاً قائماً.
--
-- ⚠️ تنبيه للمستقبل: c1prof_own كانت تمنح المشرف حق التعديل والحذف أيضاً،
--    وcycle1_admin_select تمنحه القراءة وحدها. فلو أضفتَ يوماً ميزة
--    «المشرف يُصلح ملف معلمة» أو «يحذف حساب معلمة» فستفشل حتى تُضيف سياسة.
--    وقتها أخبرني وأكتبها.

drop policy if exists c1prof_own on public.cycle1_profiles;


