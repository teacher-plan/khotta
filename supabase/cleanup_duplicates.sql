-- ─────────────────────────────────────────────────────────────
-- ① ثلاثة فهارس متطابقة على curriculum  — آمن، أنصح به
-- ─────────────────────────────────────────────────────────────
-- الثلاثة على (semester, subject, grade, sort) بلا فرق بينها:
--   idx_curriculum_lookup · idx_curriculum_path · curriculum_lookup
--
-- الأخير أنشأتُه أنا في ملف إعادة البناء دون أن أعلم بوجود الاثنين — خطأ
-- مني، فقد كان عليّ أن أستخرج البنية قبل أن أكتب. وأُسقطه هنا مع الثالث.
--
-- الأثر: كل إضافة أو تعديل في المنهج (٢٨٩٣ صفاً) تُحدّث ثلاثة فهارس بدل
-- واحد. لا خطر، لكنه عمل مضاعف بلا مقابل.

drop index if exists public.curriculum_lookup;      -- الذي أضفتُه
drop index if exists public.idx_curriculum_path;    -- مطابق للباقي
-- يبقى idx_curriculum_lookup وحده — وهو كافٍ تماماً


-- ─────────────────────────────────────────────────────────────
-- ② سياسات مكرّرة على book_sources  — آمن
-- ─────────────────────────────────────────────────────────────
-- زوجان متطابقان في الأثر. نُبقي الاسمين الأوضح ونُسقط القديمين.

drop policy if exists "read book_sources"  on public.book_sources;
drop policy if exists "admin write book_sources" on public.book_sources;
-- يبقى: booksrc_read · booksrc_admin_write


-- ─────────────────────────────────────────────────────────────
-- ③ سياسة زائدة على cycle1_profiles  — آمن
