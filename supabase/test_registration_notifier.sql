-- تُهرَّب، ويُرَدّ الطلب بـ400 فلا تصل الرسالة ولا يظهر خطأ. فإن وصلتكِ
-- الرسالة سليمةً فقد ثبت أن التهريب يعمل على الطريق الحقيقي لا في اختباري.

INSERT INTO pre_registrations (name, phone, email, stage)
