-- ═══ الخطوة ٢: ماذا جرى؟ (بعد ~١٠ ثوانٍ) ═════════════════════════
-- انتظري عشر ثوانٍ ثم نفّذي هذا. المطلوب: status_code = 200،
-- و«أُرسل التنبيه» = نعم.

-- ٢أ — هل عُلِّم الحجز مُرسَلاً؟
SELECT name AS "الحجز",
       CASE WHEN notified_at IS NULL THEN '❌ لا' ELSE '✅ نعم' END AS "أُرسل التنبيه"
FROM pre_registrations
WHERE email = 'khotta.test.delete@gmail.com';

-- ٢ب — بماذا ردّ الوكيل؟ (المطلوب: 200 و {"ok":true,"sent":1})
SELECT id, status_code AS "الرمز", left(content, 200) AS "المحتوى", error_msg AS "الخطأ"
FROM net._http_response
ORDER BY id DESC
LIMIT 3;

-- إن كان ٢ب فارغاً تماماً فالمُشغِّل لم يُطلق أصلاً — أبلغيني.
-- وإن كان الرمز 401 فمفتاح الخزانة لا يطابق مفتاح المشروع.


-- ═══ الخطوة ٣: التنظيف ═══════════════════════════════════════════
