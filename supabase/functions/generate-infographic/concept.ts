// يبني تعليمات الخريطة. src: { lesson, unit, summary, exam, skeleton? }
export function conceptPrompt(o: Any, src: Any, meta: { grade: string; subject: string; age: number; aspect: string }): string {
  const t = TYPES[o.type] ? o.type : "concept";
  const sk = src.skeleton ? JSON.stringify(src.skeleton) : "";
  const e = src.exam || {};
  const facts = [
    src.summary ? "ملخّص صفحات الدرس:\n" + String(src.summary).slice(0, 3500) : "",
    e.rules?.length ? "القواعد والتعريفات كما وردت:\n- " + e.rules.slice(0, 10).join("\n- ") : "",
    e.vocabulary?.length ? "المصطلحات:\n- " + e.vocabulary.slice(0, 12).map((v: Any) => v.ar + (v.def ? ": " + v.def : "")).join("\n- ") : "",
  ].filter(Boolean).join("\n\n");
  return [
    `ارسم صورةً واحدة: ${TYPES[t]}`,
    `الموضوع: درس «${src.lesson}» من «${src.unit}» — مادة ${meta.subject}، الصف ${meta.grade}${meta.age ? " (عمر " + meta.age + " سنوات)" : ""}، منهج سلطنة عُمان. عنوان الصورة الظاهر هو اسم الدرس فقط.`,
    "المحتوى: من صفحات الدرس وحدها كما في النصّ أدناه. لا تُضف معلومة ليست فيه، ولا أسئلة ولا تمارين.",
    sk ? `هيكل المفاهيم الجاهز (التزم بكلماته العربية حرفياً، ويجوز اختصاره بحسب مستوى التفصيل):\n${sk}` : "",
    facts,
    `مستوى التفصيل: ${DETAIL[String(o.detail)] || DETAIL["2"]}`,
    `النمط البصري: ${STYLES[o.style] || STYLES.cartoon}`,
    `الرسوم: ${ART[o.art] || ART.rich}`,
    `الألوان: ${COLORS[o.colors] || COLORS.vivid}`,
    t === "concept" && o.links === false ? "لا تكتب عبارات ربط على الأسهم — أسهم فقط." : "",
    o.student === "gaps"
      ? "نسخة الطالب: اترك نحو ثلث الصناديق فارغةً تماماً (بإطارها فقط) ليكملها الطالب من ذاكرته، وأبقِ العنوان والمفاهيم الرئيسية مكتوبة."
      : "",
    `المقاس: ${meta.aspect === "16:9" ? "أفقي عريض — وزّع الخريطة عرضياً" : meta.aspect === "1:1" ? "مربع" : "عمودي (مناسب لورقة A4) — وزّع الخريطة طولياً"}.`,
    "شروط الكتابة (الأهم): كل النصوص بالعربية الفصحى بخطٍّ عريض كبير واضح، صحيحة إملائياً حرفاً حرفاً كما في الهيكل والنصّ أعلاه، من اليمين إلى اليسار. كلمات قليلة في كل عقدة (لا جُمل طويلة). الأرقام بالأرقام العربية (٠١٢٣٤٥٦٧٨٩). لا نصّ إنجليزي إلا للمصطلحات بين قوسين. لا تكرّر الكلمة نفسها في موضعين.",
    "الرسوم: الهوية العُمانية إن ظهرت شخصيات، بلا أي تلامسٍ جسدي بين الشخصيات، ولا صور فوتوغرافية.",
    "قبل الإخراج النهائي راجع كل كلمةٍ مكتوبة إملائياً، وتأكّد أن كل سهمٍ وعبارة ربطٍ في موضعها الصحيح وأن الخريطة غير مزدحمة.",
    o.extra ? `توجيهات المعلّم (لها الأولوية ما لم تخالف الشروط أعلاه): ${String(o.extra).slice(0, 800)}` : "",
    subjectRules(meta.subject, "infographic"),
  ].filter(Boolean).join("\n\n");
}
