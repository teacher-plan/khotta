-- صلاحية الحسابات: تجربة مجانية مؤقّتة + اشتراكٌ فصليّ محدود المدّة
--
-- الفكرة: بوّابة الدخول اليوم هي وجود صفٍّ في allowed_emails (انظر منطق
-- تسجيل الدخول في cycle1.html). فبدل بناء فحصٍ جديد، نُضيف تاريخ انتهاء
-- ونجعل سياسة RLS القائمة تُخفي الصفّ عن صاحبته بعد انتهائه — فتُرفَض
-- تلقائياً برسالة «هذا البريد غير مصرّح له بالدخول» نفسها، بلا سطرٍ
-- واحدٍ من التعديل في منطق الدخول.
--
-- ⚠️ لماذا الإخفاء لا الحذف: الحذف يُدمّر بيانات إذنٍ حقيقية لمعلّماتٍ
-- دافعات، ولا يمكن التراجع عنه لو أخطأ حسابُ تاريخٍ أو منطقةٌ زمنية.
-- الإخفاء يُنتج نفس الأثر تماماً، لكنه: قابلٌ للتراجع فوراً (امسح
-- expires_at فيعود الدخول)، ومرئيٌّ للمدير في اللوحة، ومحفوظٌ كسجلّ.
--
-- ⚠️ لا حساب قائم يتأثّر: expires_at الفارغ = صلاحيةٌ دائمة، وكل الصفوف
-- الحالية تبقى فارغةً بعد هذه الهجرة. أي ضبطٍ لتواريخ الحسابات القائمة
-- قرارٌ منفصلٌ صريح، لا أثرَ جانبيّ لهذه الهجرة.
-- ════════════════════════════════════════════════════════════════════

ALTER TABLE public.allowed_emails
  ADD COLUMN IF NOT EXISTS expires_at timestamptz;

COMMENT ON COLUMN public.allowed_emails.expires_at IS
  'انتهاء صلاحية الدخول. NULL = دائم (السلوك الافتراضي لكل الحسابات القائمة). عند تجاوز التاريخ تُخفي سياسة allowed_own_select الصفَّ عن صاحبته فيُرفَض دخولها، مع بقاء كل بياناتها سليمةً وقابليةِ الإرجاع بمسح هذا الحقل.';

-- فهرسٌ للصفوف المؤقّتة وحدها — الحسابات الدائمة (NULL) هي الأغلبية
-- ولا حاجة لفهرستها؛ يخدم استعلامات «ما الذي يوشك على الانتهاء؟».
CREATE INDEX IF NOT EXISTS idx_allowed_emails_expires_at
  ON public.allowed_emails (expires_at)
  WHERE expires_at IS NOT NULL;

-- ─────────────────────────────────────────────────────────────────────
-- تعديل سياسة القراءة: تُضاف شرطيّة الانتهاء إلى مسار «المعلّمة تقرأ
-- بريدها»، ويبقى مسار المدير (is_app_admin) بلا قيدٍ كي تظهر له الحسابات
-- المنتهية في اللوحة ويستطيع تمديدها.
--
-- منقولةٌ حرفياً عن الأصل في 00000000_base_tables_reconstructed.sql مع
-- إضافة الشرط وحده — لا تغيير في النطاق (for select to authenticated).
-- ─────────────────────────────────────────────────────────────────────
DROP POLICY IF EXISTS allowed_own_select ON public.allowed_emails;
CREATE POLICY allowed_own_select ON public.allowed_emails
  FOR SELECT TO authenticated
  USING (
    is_app_admin()
    OR (
      lower(email) = lower(auth.jwt()->>'email')
      AND (expires_at IS NULL OR expires_at > now())
    )
  );

