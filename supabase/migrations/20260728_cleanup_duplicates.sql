drop index if exists public.curriculum_lookup;
drop index if exists public.idx_curriculum_path;


-- ─────────────────────────────────────────────────────────────
-- ② إزالة سياسات مكررة على book_sources
-- ─────────────────────────────────────────────────────────────
-- أربع سياسات في الإنتاج، زوجان متطابقان:
-- بقي: "read book_sources" و "admin write book_sources"
-- حذف: booksrc_read (نسخة مكررة)
-- حذف: booksrc_admin_write (نسخة مكررة)

drop policy if exists booksrc_read on public.book_sources;
drop policy if exists booksrc_admin_write on public.book_sources;


