-- إعادة تأكيد سياسة قراءة c1_messages — بلاغٌ من مشرفةٍ حقيقية: رسالةٌ
-- خاصةٌ لمعلمةٍ واحدة وصلت لكل معلمات الحلقة الأولى، وظهرت لكلٍّ منهنّ
-- موسومةً «خاصة لك».
--
-- السبب المؤكَّد في الواجهة (cycle1.html): فلتر العرض كان يتحقق من
-- target_subject فقط، لا من target_user_id — أُصلح في نفس الدفعة.
-- هذه الهجرة طبقةُ دفاعٍ ثانية: تعيد فرض سياسة القراءة الصحيحة على
-- القاعدة نفسها (target_user_id فارغ أو يطابق auth.uid() أو المشرف)،
-- تحسّباً لانحرافها عن الأصل في 20260719_c1_correspondence.sql — لا
-- تغيير في المنطق المقصود، إعادة تطبيقٍ حرفية فقط.
-- ════════════════════════════════════════════════════════════════════

drop policy if exists "c1msg_read" on c1_messages;
create policy "c1msg_read" on c1_messages
  for select to authenticated
  using (target_user_id is null or target_user_id = auth.uid() or is_app_admin());
