-- إعادة تعيين أدلةٍ تبيّن أن فهرسها بمستوى الوحدة لا الدرس (فمطابقتها صفرٌ
-- رغم وجود فهرسٍ كامل)، أو أعادها الفحص الجذري إلى index_failed بعد إصلاح
-- ٢٠٢٦٠٩٠٧ (index-teacher-guide) الذي:
--  (أ) يرفض دفعةً لا تبلغ حدّاً أدنى من المطابقات الفعلية بدل قبول أول
--      فهرسٍ جزئي،
--  (ب) يوزّع دروس الوحدة على مداها عند وجود فهرسٍ بعناوين الوحدات فقط،
--  (ج) لا يُسقط المطابقات المتراكمة عند خطأٍ عابر من المزوّد.
--
-- الأدلة المتضرّرة فعلياً (بالفحص المباشر عبر GitHub Actions):
--  - الرياضيات ص١/ص٤: index_failed بعد خطأٍ عابر أسقط التراكم القديم.
--  - الهوية والمواطنة ص٣/ص٤: فهرسٌ كاملٌ لكن صفر مطابقة (فهرس وحداتٍ فقط).
--  - ديني حياتي ص٤: نفس النمط (toc=36 بند، صفر مطابقة).

UPDATE teacher_guides
SET status = 'uploaded', updated_at = now()
WHERE (subject = 'الرياضيات' AND grade IN (1, 4))
   OR (subject = 'الهوية والمواطنة' AND grade IN (3, 4))
   OR (subject = 'ديني حياتي' AND grade = 4);

