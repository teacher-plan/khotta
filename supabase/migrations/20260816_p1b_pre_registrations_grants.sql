-- اكتُشف بالاختبار الحيّ لا بالقراءة: بعد تطبيق تلك الهجرة، ظلّ إدراج
-- anon (نموذج التسجيل العامّ في landing.html) يفشل بـ 42501 نفسها.
-- السبب: سياسة RLS تُقيّد الصفوف، لكنها لا تُنشئ الامتياز على الجدول
-- نفسه — Postgres يطلب الاثنين معاً (GRANT ثم RLS يُضيّق فوقه). وهذا
-- الجدول تحديداً بلا امتيازاتٍ أصلاً لـ anon/authenticated (على الأرجح
-- REVOKE سابقة غير متتبَّعة في أي هجرة، يوازي ما فعلته
-- 20260816_p0_rls_internal_tables.sql عمداً بالجداول الداخلية — هنا
-- كانت غير مقصودة، وأبطلت التسجيل العامّ بالكامل حتى هذه الهجرة).
-- ════════════════════════════════════════════════════════════════════

GRANT INSERT ON public.pre_registrations TO anon;
GRANT SELECT, UPDATE, DELETE ON public.pre_registrations TO authenticated;
-- لا INSERT لـ authenticated: التسجيل العامّ يمرّ بـ anon فقط، ولا حاجة
-- لمعلّمةٍ مسجَّلة أن تُنشئ تسجيلاً جديداً بحسابها.

COMMENT ON TABLE public.pre_registrations IS
  'طلبات الاشتراك قبل تفعيل الحساب — anon يُدرج فقط (GRANT INSERT + RLS WITH CHECK)، والقراءة والتعديل للمشرف حصراً عبر RLS.';
