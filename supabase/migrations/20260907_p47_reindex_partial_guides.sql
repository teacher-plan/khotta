-- السبب: index-teacher-guide كانت تقبل أوّل دفعةٍ فيها أي بندٍ فهرسي —
-- حتى لو كانت فهرس وحدةٍ فرعيةٍ من بندين أو ثلاثة فقط، لا الفهرس الرئيسي
-- لدروس الفصل كاملةً — فتتوقّف عن البحث مبكراً وتحفظ فهرساً ناقصاً جداً.
-- هذا ظهر فعلياً في ثلاثة أدلة (toc أقل من ٤ بنودٍ بينما شقيقاتها من نفس
-- المادة بين ١٦-٥٢ بنداً)، وهذا سبب هبوط نسبة التغطية من ٨٥٫٧٪ إلى ٦٦٪.
-- الدالة أُصلحت (20260907، index-teacher-guide) لترفض أي دفعةٍ تحت حدٍّ
-- أدنى وتواصل البحث؛ هذه الهجرة فقط تُعيد تعيين الأدلة الثلاثة المتضرّرة
-- فعلياً كي تُعاد فهرستها بالمنطق الجديد.

UPDATE teacher_guides
SET status = 'uploaded', updated_at = now()
WHERE (subject = 'الرياضيات' AND grade IN (1, 3, 4))
   OR (subject = 'الهوية والمواطنة' AND grade = 2);

