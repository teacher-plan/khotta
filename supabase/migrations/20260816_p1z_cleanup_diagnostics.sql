-- تنظيفٌ ختامي بعد جولة التشخيص الحيّة على pre_registrations.
--
-- الخلاصة: RLS كانت سليمة طوال الوقت. سبب فشل الاختبار كان في منهجية
-- الاختبار نفسها لا في الهجرة — Prefer: return=representation يطلب من
-- Postgres RETURNING الصفّ المُدرَج، وRETURNING يستوجب أن يمرّ الصفّ
-- بسياسة SELECT أيضاً؛ ولمّا كان anon بلا سياسة SELECT على هذا الجدول
-- (بالتصميم — لا يصحّ أن تقرأ زائرةٌ تسجيلات غيرها)، فشل الإدراج
-- الاختباري رغم صحّته. مسار الإنتاج الحقيقي (landing.html) يستدعي
-- .insert() بلا .select()‎، أي بلا RETURNING، فلم يتأثر قط.
-- ════════════════════════════════════════════════════════════════════

-- إسقاط جدول التشخيص المؤقّت.
DROP TABLE IF EXISTS public._audit_sanity;

-- حذف صفوف الاختبار التي أدرجتُها بمفتاح anon أثناء التشخيص —
-- مُعلَّمةٌ صراحةً بالاسم فلا خطر من حذفها انتقائياً.
DELETE FROM public.pre_registrations
  WHERE name = '__AUDIT_TEST_DO_NOT_ACTIVATE__';
