insert into public.curriculum (semester,grade,subject,unit,lesson,sort,page,book_no)
  select 'الفصل الأول',9,'اللغة العربية',unit,lesson,sort,page,1 from _ar9 order by sort;
update public.book_sources set offset_pages=3, updated_at=now()
  where grade='9' and subject='اللغة العربية' and semester='الفصل الأول' and book_no=1;
update public.teacher_guides g set
  toc = (select jsonb_agg(e order by (e->>'guide_page')::int) from (
          select jsonb_build_object('guide_unit',a.unit,'guide_lesson',a.lesson,'guide_page',a.gpage,'matched_curriculum_id',c.id,'confidence',a.conf) e
          from _ar9 a join public.curriculum c on c.grade=9 and c.subject='اللغة العربية' and c.semester='الفصل الأول' and c.sort=a.sort
          union all
          select jsonb_build_object('guide_unit','معالجات وحدات الجزء الثاني','guide_lesson',null,'guide_page',59,'matched_curriculum_id',null,'confidence','high')
        ) t),
  offset_pages=2, status='indexed', indexed_at=now(), updated_at=now()
  where grade=9 and subject='اللغة العربية' and semester='الفصل الأول';
select (select count(*) from public.curriculum where grade=9 and subject='اللغة العربية' and semester='الفصل الأول') cur_rows,
       (select offset_pages from public.book_sources where grade='9' and subject='اللغة العربية' and semester='الفصل الأول') book_off,
       (select jsonb_array_length(toc)||' / '||status||' / off '||offset_pages from public.teacher_guides where grade=9 and subject='اللغة العربية' and semester='الفصل الأول') guide;
